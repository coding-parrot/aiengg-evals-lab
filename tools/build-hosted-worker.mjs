import fs from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const target=process.argv[2];if(!target)throw new Error('Pass the Sites checkout directory');
const read=p=>fs.readFile(path.join(root,p),'utf8');
const html=await read('cohort.html'),prompt=(await read('prompts/tutor-starting-system.txt')).replace(/\r\n/g,'\n'),cards=JSON.parse(await read('samples/sanitized-source-cards.json'));
const decisions=(await read('tools/decisions.mjs')).replaceAll('export function','function');
const handler=(await read('hosting/worker.mjs')).replace(/^import .*;\r?\n/gm,'');
const bundle=`const HTML=${JSON.stringify(html)};\nconst PROMPT=${JSON.stringify(prompt)};\nconst CARDS=${JSON.stringify(cards)};\n${decisions}\n${handler}`;
await fs.mkdir(path.join(target,'worker'),{recursive:true});await fs.writeFile(path.join(target,'worker/index.js'),bundle);
await fs.writeFile(path.join(target,'package.json'),JSON.stringify({name:'aiengg-evals-hosted',private:true,type:'module',scripts:{build:'node scripts/build.mjs'}},null,2));
await fs.mkdir(path.join(target,'scripts'),{recursive:true});
await fs.writeFile(path.join(target,'scripts/build.mjs'),`import fs from 'node:fs/promises';
await fs.mkdir('dist/server',{recursive:true});await fs.mkdir('dist/.openai',{recursive:true});
await fs.copyFile('worker/index.js','dist/server/index.js');await fs.copyFile('.openai/hosting.json','dist/.openai/hosting.json');
console.log('Built hosted lab Worker.');\n`);
await fs.writeFile(path.join(target,'.gitignore'),'dist/\nnode_modules/\n.env*\n.openai/local-*\n.sites-*\n');
console.log('Prepared Worker source without runtime secrets.');
